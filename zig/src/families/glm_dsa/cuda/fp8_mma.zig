        const slot = try kernelAccumulatorIndex(warp, visit);
        try std.testing.expect(tile < 128);
        try std.testing.expect(slot < 16);
        // The former CUDA expression acc[t] fails this check for 14/16 visits.
        if (visit >= 2) try std.testing.expectError(error.Bounds, boundsCheckAccumulatorIndex(tile));
