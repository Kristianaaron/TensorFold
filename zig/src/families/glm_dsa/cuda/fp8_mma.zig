pub const Group = enum { block128, mxfp8_32 };
pub const block_k: usize = 128;
pub const mxfp8_group: usize = 32;
pub const dynamic_shared_bytes: u32 = 64 * 1024;

pub const MmaFragment = struct { a: [4]u32, b: [2]u32, c: [4]f32 };

/// Byte locations for PTX ISA 9.4 mma.sync.m16n8k32.e4m3 fragments (9.7.16.5.10).
/// lane = 4*groupID + thread-in-group. A rows are group/group+8 with K offsets 0/16;
/// B's row is group with K offsets 0/16; C rows are group/group+8 and columns 2*tig+{0,1}.
pub fn fragmentAIndex(lane: usize, row_tile: usize, k_tile: usize, reg: usize, byte: usize) usize {
    const group_id = lane >> 2;
    const thread_in_group = lane & 3;
    const row = row_tile + group_id + (if (reg & 1 != 0) @as(usize, 8) else 0);
    const k = k_tile + 4 * thread_in_group + byte + (if (reg >= 2) @as(usize, 16) else 0);
    return row * 128 + k;
}

pub fn fragmentBIndex(lane: usize, col_tile: usize, k_tile: usize, reg: usize, byte: usize) usize {
    const group_id = lane >> 2;
    const thread_in_group = lane & 3;
    const col = col_tile + group_id;
    const k = k_tile + 4 * thread_in_group + byte + (if (reg == 1) @as(usize, 16) else 0);
    return k * 8 + col;
}

pub fn fragmentCIndex(lane: usize, row_tile: usize, col_tile: usize, reg: usize) usize {
    const group_id = lane >> 2;
    const thread_in_group = lane & 3;
    const row = row_tile + group_id + (if (reg >= 2) @as(usize, 8) else 0);
    const col = col_tile + 2 * thread_in_group + (reg & 1);
    return row * 8 + col;
}

/// Reconstructs one 16x8x128 product from lane-owned PTX fragments, then applies
/// the block scale once. `xq` is [16][128] in activation fragment order and `w`
/// is FP8G packed for at least 8 output rows and 128 K values.
/// This is a sequential FP32 reference for one block; it does not claim to
/// reproduce the tensor-core reduction order. PF0 compares with a tolerance.
pub fn emulateTileBlock(xq: []const u8, w: []const u8, scale: f32, out: []f32) error{Shape}!void {
    if (xq.len != 16 * 128 or w.len < 64 * 128 or out.len != 16 * 8) return error.Shape;
    var a_values: [16 * 128]u8 = @splat(0);
    var b_values: [128 * 8]u8 = @splat(0);
    for (0..32) |lane| for (0..4) |h| {
        for (0..4) |reg| for (0..4) |byte| {
            const at = fragmentAIndex(lane, 0, h * 32, reg, byte);
            const row = at / 128;
            const k = at % 128;
            a_values[at] = xq[row * 128 + activationFragmentIndex(row, k) % 128];
        };
        for (0..2) |reg| for (0..4) |byte| {
            const at = fragmentBIndex(lane, 0, h * 32, reg, byte);
            const k = at / 8;
            const col = at % 8;
            b_values[at] = w[weightFragmentIndex(col, k, 128)];
        };
    };
    @memset(out, 0);
    for (0..32) |lane| for (0..4) |reg| {
        const at = fragmentCIndex(lane, 0, 0, reg);
        const row = at / 8;
        const col = at % 8;
        var partial: f32 = 0;
        for (0..128) |k| {
            const av = @as(f32, @floatCast(e4m3(a_values[row * 128 + k])));
            const bv = @as(f32, @floatCast(e4m3(b_values[k * 8 + col])));
            partial = partial + av * bv;
        }
        out[at] = @mulAdd(f32, partial, scale, 0);
    };
}

/// Models the kernel's warp-to-tile loop and its 16-element local accumulator.
/// The returned index is the register-array index, not the linear tile number.
pub fn kernelAccumulatorIndex(warp: usize, visit: usize) error{Bounds}!usize {
    if (warp >= 8 or visit >= 16) return error.Bounds;
    const tile = warp + 8 * visit;
    if (tile >= 128) return error.Bounds;
    return visit;
}

/// Independent host model of one CTA's tile ownership. Each warp walks its
/// 16 kernel tiles, bounds-checks the local accumulator slots, and records
/// the 128x128 output ownership generated by group/tig/c register arithmetic.
pub fn modelKernelTileVisits() error{Bounds}!void {
    var seen: [128]bool = @splat(false);
    for (0..8) |warp| for (0..16) |visit| {
        const tile = warp + 8 * visit;
        const slot = try kernelAccumulatorIndex(warp, visit);
        if (slot >= 16 or tile >= seen.len or seen[tile]) return error.Bounds;
        seen[tile] = true;
        const mt = tile / 16;
        const nt = tile % 16;
        for (0..32) |lane| for (0..4) |c| {
            const group = lane >> 2;
            const tig = lane & 3;
            const row = mt * 16 + group + (if (c >= 2) @as(usize, 8) else 0);
            const col = nt * 8 + 2 * tig + (c & 1);
            if (row >= 128 or col >= 128) return error.Bounds;
        };
    };
    for (seen) |tile_seen| if (!tile_seen) return error.Bounds;
}

pub fn activationFragmentIndex(row: usize, k: usize) usize {
    const q = (k % 8) / 2;
    const odd = k % 2;
    const hi = (k % 16) / 8;
    const j = odd + 2 * hi;
    _ = row;
    return (k / 16) * 16 + 4 * q + j;
}

pub fn weightFragmentIndex(row: usize, k: usize, k_width: usize) usize {
    const kin = k % 32;
    const a = (row % 64) / 8;
    const h = (k % 64) / 32;
    const lane_lo = (kin & 7) >> 1;
    const b = (kin >> 4) * 4 + (kin & 1) + ((kin & 8) >> 2);
    const lane = (row % 8) * 4 + lane_lo;
    return (((((row / 64) * (k_width / 64) + k / 64) * 8 + a) * 32 + lane) * 2 + h) * 8 + b;
}

/// Convert packed FP8G codes to backend row-major [N][K] order.
/// The caller can discard the packed allocation after this one pass.
pub fn unpackRowMajorWeights(out: []u8, packed_codes: []const u8, n: usize, k: usize) error{Shape}!void {
    if (n == 0 or k == 0 or k % 128 != 0 or out.len != n * k or packed_codes.len != paddedRows(n) * k) return error.Shape;
    for (0..n) |row| for (0..k) |col| {
        out[row * k + col] = packed_codes[weightFragmentIndex(row, col, k)];
    };
}

/// Replace an owned FP8G buffer with the smaller backend row-major allocation after conversion succeeds.
pub fn replacePackedWeights(allocator: std.mem.Allocator, packed_codes: []u8, n: usize, k: usize) ![]u8 {
    const row_major = try allocator.alloc(u8, n * k);
    errdefer allocator.free(row_major);
    try unpackRowMajorWeights(row_major, packed_codes, n, k);
    allocator.free(packed_codes);
    return row_major;
}

/// Convert quantizer fragment-order activations to the row-major matrix consumed by CUTLASS/cuBLASLt.
pub fn unpackRowMajorActivations(out: []u8, fragment_codes: []const u8, m: usize, k: usize) error{Shape}!void {
    if (m == 0 or k == 0 or k % 128 != 0 or out.len != m * k or fragment_codes.len != m * k) return error.Shape;
    for (0..m) |row| for (0..k) |col| {
        out[row * k + col] = fragment_codes[row * k + activationFragmentIndex(row, col)];
    };
}

fn paddedRows(n: usize) usize {
    return (n + 63) / 64 * 64;
}

/// cuBLASLt BLK128x128 scale order for A = W: K blocks are major,
/// and the K-block extent is padded to a multiple of four as required by CUDA 13.
pub fn packCublasLtWeightScales(out: []f32, scale_inv: []const f32, n: usize, k: usize) error{Shape}!void {
    if (n == 0 or k == 0 or n % 128 != 0 or k % 128 != 0) return error.Shape;
    const nb = n / 128;
    const kb = k / 128;
    const kp = (kb + 3) / 4 * 4;
    if (scale_inv.len != nb * kb or out.len != nb * kp) return error.Shape;
    for (0..nb) |nr| for (0..kp) |kr| {
        out[nr * kp + kr] = if (kr < kb) scale_inv[nr * kb + kr] else 1.0;
    };
}

/// cuBLASLt VEC128 scales for B = X are token-major: every 128-K group stores exec-M contiguous scales.
pub fn packCublasLtActivationScales(out: []f32, row_major: []const f32, m: usize, k: usize) error{Shape}!void {
    if (m == 0 or k == 0 or k % 128 != 0 or row_major.len != m * (k / 128) or out.len != row_major.len) return error.Shape;
    const groups = k / 128;
    for (0..m) |row| for (0..groups) |group| {
        out[group * m + row] = row_major[row * groups + group];
    };
}

pub const Fp8Mma = struct {
    mod: Module,
    quant_fn: Function,
    mxfp8_quant_fn: Function,
    gemm_fn: Function,
    scalar_fn: Function,
    peak_bf16_fn: Function,
    peak_fp8_fn: Function,
    raw_fp8_probe_fn: Function,
    raw_bf16_probe_fn: Function,
    mxfp8_gemm_fn: Function,

    pub fn load(d: *const Driver) !Fp8Mma {
        if (!cuda.kernels.available) return error.BuiltWithoutKernels;
        var mod = try Module.load(d, cuda.kernels.glm53_fp8_mma);
        errdefer mod.unload();
        const gemm_fn = try mod.function("tf_glm53_fp8_mma");
        try gemm_fn.allowDynamicShared(dynamic_shared_bytes);
        return .{
            .mod = mod,
            .quant_fn = try mod.function("tf_glm53_act_q8"),
            .mxfp8_quant_fn = try mod.function("tf_glm53_act_mxfp8"),
            .gemm_fn = gemm_fn,
            .scalar_fn = try mod.function("tf_glm53_fp8_mma_scalar"),
            .peak_bf16_fn = try mod.function("tf_glm53_peak_bf16"),
            .peak_fp8_fn = try mod.function("tf_glm53_peak_fp8"),
            .raw_fp8_probe_fn = try mod.function("tf_glm53_raw_fp8_acc_probe"),
            .raw_bf16_probe_fn = try mod.function("tf_glm53_raw_bf16_acc_probe"),
            .mxfp8_gemm_fn = try mod.function("tf_glm53_fp8_mma_mx"),
        };
    }

    pub fn unload(g: *Fp8Mma) void {
        g.mod.unload();
    }

    /// Quantizes bf16 [M,K] to fragment-order E4M3 and per-row 1x128 scales.
    pub fn quantize(g: *const Fp8Mma, s: Stream, x: u64, ldx: usize, m: usize, k: usize, xq: u64, xs: u64) !void {
        if (k == 0 or k % block_k != 0 or ldx < k) return error.Shape;
        if (m == 0) return;
        var a: cuda.Args = .{};
        a.add(x);
        a.add(@as(i64, @intCast(ldx)));
        a.add(@as(i32, @intCast(m)));
        a.add(@as(i32, @intCast(k)));
        a.add(xq);
        a.add(xs);
        try cuda.launch.launch(g.quant_fn, .{ .grid = .{ .x = @intCast(m), .y = @intCast(k / block_k), .z = 1 }, .block = .{ .x = 128 } }, s, &a);
    }

    /// Optional MXFP8 activation quantizer: per-row 1x32 scales encoded as UE8M0 bytes.
    pub fn quantizeMxfp8(g: *const Fp8Mma, s: Stream, x: u64, ldx: usize, m: usize, k: usize, xq: u64, xs: u64) !void {
        if (k == 0 or k % mxfp8_group != 0 or ldx < k) return error.Shape;
        if (m == 0) return;
        var a: cuda.Args = .{};
        a.add(x);
        a.add(@as(i64, @intCast(ldx)));
        a.add(@as(i32, @intCast(m)));
        a.add(@as(i32, @intCast(k)));
        a.add(xq);
        a.add(xs);
        try cuda.launch.launch(g.mxfp8_quant_fn, .{ .grid = .{ .x = @intCast(m), .y = @intCast(k / mxfp8_group), .z = 1 }, .block = .{ .x = 128 } }, s, &a);
    }

    /// W8A8 block-scaled GEMM. W is the FP8G fragment-order matrix; output is contiguous [M,N].
    /// Scales are consumed outside MMA and applied once per 128-K partial.
    pub fn run(g: *const Fp8Mma, s: Stream, xq: u64, xs: u64, w: u64, ws: u64, out: u64, m: usize, n: usize, k: usize, output_f32: bool) !void {
        if (m == 0 or n == 0 or k == 0 or k % block_k != 0) return error.Shape;
        var a: cuda.Args = .{};
        a.add(xq);
        a.add(xs);
        a.add(w);
        a.add(ws);
        a.add(out);
        a.add(@as(i32, @intCast(m)));
        a.add(@as(i32, @intCast(n)));
        a.add(@as(i32, @intCast(k)));
        a.add(@as(i32, @intFromBool(output_f32)));
        try cuda.launch.launch(g.gemm_fn, .{ .grid = .{ .x = @intCast((n + 127) / 128), .y = @intCast((m + 127) / 128), .z = 1 }, .block = .{ .x = 256 }, .shared = dynamic_shared_bytes }, s, &a);
    }

    /// Scalar bit oracle: one thread per output element, with sequential FP32 partials.
    pub fn runScalar(g: *const Fp8Mma, s: Stream, xq: u64, xs: u64, w: u64, ws: u64, out: u64, m: usize, n: usize, k: usize, output_f32: bool) !void {
        if (m == 0 or n == 0 or k == 0 or k % block_k != 0) return error.Shape;
        var a: cuda.Args = .{};
        a.add(xq);
        a.add(xs);
        a.add(w);
        a.add(ws);
        a.add(out);
        a.add(@as(i32, @intCast(m)));
        a.add(@as(i32, @intCast(n)));
        a.add(@as(i32, @intCast(k)));
        a.add(@as(i32, @intFromBool(output_f32)));
        try cuda.launch.launch(g.scalar_fn, .{ .grid = .{ .x = @intCast((m * n + 255) / 256), .y = 1, .z = 1 }, .block = .{ .x = 256 } }, s, &a);
    }

    /// Register-only throughput loop; each CTA keeps four independent accumulators per warp.
    pub fn runPeak(g: *const Fp8Mma, s: Stream, fp8: bool, iterations: usize, sms: usize, sink: u64) !void {
        if (iterations == 0 or sms == 0) return error.Shape;
        var a: cuda.Args = .{};
        a.add(@as(i32, @intCast(iterations)));
        a.add(sink);
        const f = if (fp8) g.peak_fp8_fn else g.peak_bf16_fn;
        try cuda.launch.launch(f, .{ .grid = .{ .x = @intCast(sms * 4), .y = 1, .z = 1 }, .block = .{ .x = 256 } }, s, &a);
    }

    /// One raw tensor-core accumulator experiment per block. A/B words contain
    /// one nonzero fragment byte/half in the lane-0 k=0 position.
    pub fn runRawAccumulatorProbe(g: *const Fp8Mma, s: Stream, bf16: bool, a_words: u64, b_words: u64, seeds: u64, iterations: usize, out: u64, count: usize) !void {
        if (iterations == 0 or count == 0) return error.Shape;
        var a: cuda.Args = .{};
        a.add(a_words);
        a.add(b_words);
        a.add(seeds);
        a.add(@as(i32, @intCast(iterations)));
        a.add(out);
        const f = if (bf16) g.raw_bf16_probe_fn else g.raw_fp8_probe_fn;
        try cuda.launch.launch(f, .{ .grid = .{ .x = @intCast(count), .y = 1, .z = 1 }, .block = .{ .x = 32 } }, s, &a);
    }

    /// Explicit MXFP8 activation path; its 32-value scales are UE8M0 bytes.
    pub fn runMxfp8(g: *const Fp8Mma, s: Stream, xq: u64, xs: u64, w: u64, ws: u64, out: u64, m: usize, n: usize, k: usize, output_f32: bool) !void {
        if (m == 0 or n == 0 or k == 0 or k % block_k != 0 or k % mxfp8_group != 0) return error.Shape;
        var a: cuda.Args = .{};
        a.add(xq);
        a.add(xs);
        a.add(w);
        a.add(ws);
        a.add(out);
        a.add(@as(i32, @intCast(m)));
        a.add(@as(i32, @intCast(n)));
        a.add(@as(i32, @intCast(k)));
        a.add(@as(i32, @intFromBool(output_f32)));
        try cuda.launch.launch(g.mxfp8_gemm_fn, .{ .grid = .{ .x = @intCast((m * n + 255) / 256), .y = 1, .z = 1 }, .block = .{ .x = 256 } }, s, &a);
    }
};

/// E4M3 value, including subnormals. NaN encodings match the CUDA conversion contract.
pub fn e4m3(code: u8) f64 {
    if (code & 0x7f == 0x7f) return std.math.nan(f64);
    const sign: f64 = if (code & 0x80 != 0) -1 else 1;
    const e: i32 = (code >> 3) & 15;
    const m: f64 = @floatFromInt(code & 7);
    return sign * if (e == 0) m * std.math.pow(f64, 2, -9) else (1 + m / 8) * std.math.pow(f64, 2, @floatFromInt(e - 7));
}

/// Round-to-nearest-even E4M3, saturating finite values at 448.
pub fn toE4m3(x: f64) u8 {
    if (std.math.isNan(x)) return 0x7f;
    const sign: u8 = if (x < 0) 0x80 else 0;
    const a = @min(@abs(x), 448);
    if (a == 0) return sign;
    var best: u8 = 0;
    var err = std.math.inf(f64);
    for (0..127) |i| {
        const c: u8 = @intCast(i);
        const v = e4m3(c);
        if (!std.math.isNan(v) and @abs(v - a) < err) {
            best = c;
            err = @abs(v - a);
        }
    }
    if (a > e4m3(best) and best < 0x7e) {
        const up = best + 1;
        const mid = (e4m3(best) + e4m3(up)) * 0.5;
        if (a > mid or (a == mid and (best & 1) != 0)) best = up;
    }
    return sign | best;
}

/// Per row and 128 values: scale = max(amax, 1e-10)/448, matching d3_act_quant.
pub fn quantize128(input: []const f32, rows: usize, k: usize, codes: []u8, scales: []f32) error{Shape}!void {
    if (k == 0 or k % block_k != 0 or input.len != rows * k or codes.len != input.len or scales.len != rows * (k / block_k)) return error.Shape;
    for (0..rows) |r| for (0..k / block_k) |g| {
        const at = r * k + g * block_k;
        var amax: f32 = 0;
        for (input[at..][0..block_k]) |x| amax = @max(amax, @abs(x));
        const scale: f32 = @max(amax, 1e-10) / 448;
        scales[r * (k / block_k) + g] = scale;
        for (0..block_k) |i| codes[r * k + activationFragmentIndex(0, g * block_k + i)] = toE4m3(@as(f64, input[at + i] / scale));
    };
}

/// Reference for row-major E4M3 activations and FP8G-order weights. Weight rows are padded to 64;
/// weight scales have ceil(N/128) rows. Each 128-K FP32 partial is scaled and FMA'd in K-block order.
pub fn reference(xq: []const u8, xs: []const f32, w: []const u8, ws: []const f32, m: usize, n: usize, k: usize, out: []f32) error{Shape}!void {
    if (k == 0 or k % block_k != 0 or n == 0 or xq.len != m * k or xs.len != m * (k / block_k) or w.len != ((n + 63) / 64) * 64 * k or ws.len != ((n + 127) / 128) * (k / block_k) or out.len != m * n) return error.Shape;
    for (0..m) |r| for (0..n) |c| {
        var acc: f32 = 0;
        for (0..k / block_k) |g| {
            var partial: f32 = 0;
            for (g * block_k..(g + 1) * block_k) |i| partial += @as(f32, @floatCast(e4m3(xq[r * k + activationFragmentIndex(0, i)]))) * @as(f32, @floatCast(e4m3(w[weightFragmentIndex(c, i, k)])));
            const scale = ws[(c / 128) * (k / block_k) + g] * xs[r * (k / block_k) + g];
            acc = @mulAdd(f32, partial, scale, acc);
        }
        out[r * n + c] = acc;
    };
}

/// MXFP8 host activation quantization: one UE8M0 scale per 32 values, with scale rounded up to a power of two.
pub fn quantizeMxfp8(input: []const f32, rows: usize, k: usize, codes: []u8, scales: []u8) error{Shape}!void {
    if (k == 0 or k % mxfp8_group != 0 or input.len != rows * k or codes.len != input.len or scales.len != rows * (k / mxfp8_group)) return error.Shape;
    for (0..rows) |r| for (0..k / mxfp8_group) |g| {
        const at = r * k + g * mxfp8_group;
        var amax: f32 = 0;
        for (input[at..][0..mxfp8_group]) |x| amax = @max(amax, @abs(x));
        const raw_exponent: i32 = if (amax == 0) 0 else blk: {
            const fraction = std.math.frexp(@as(f64, amax / 448));
            break :blk fraction.exponent - @intFromBool(fraction.significand == 0.5);
        };
        const exponent = @max(-127, @min(127, raw_exponent));
        const scale = std.math.scalbn(@as(f32, 1), exponent);
        scales[r * (k / mxfp8_group) + g] = @intCast(@as(i32, 127) + exponent);
        for (0..mxfp8_group) |i| codes[r * k + activationFragmentIndex(0, g * mxfp8_group + i)] = toE4m3(@as(f64, input[at + i] / scale));
    };
}

/// MXFP8 activation variant against the same FP8G weights, with one activation scale per 32 K values.
pub fn referenceMxfp8(xq: []const u8, xs: []const u8, w: []const u8, ws: []const f32, m: usize, n: usize, k: usize, out: []f32) error{Shape}!void {
    if (k == 0 or k % block_k != 0 or n == 0 or xq.len != m * k or xs.len != m * (k / 32) or w.len != ((n + 63) / 64) * 64 * k or ws.len != ((n + 127) / 128) * (k / 128) or out.len != m * n) return error.Shape;
    for (0..m) |r| for (0..n) |c| {
        var acc: f32 = 0;
        for (0..k / 32) |g| {
            var partial: f32 = 0;
            for (g * 32..(g + 1) * 32) |i| partial += @as(f32, @floatCast(e4m3(xq[r * k + activationFragmentIndex(0, i)]))) * @as(f32, @floatCast(e4m3(w[weightFragmentIndex(c, i, k)])));
            const activation_scale = std.math.scalbn(@as(f32, 1), @as(i32, xs[r * (k / 32) + g]) - 127);
            const weight_scale = ws[(c / 128) * (k / 128) + g / 4];
            acc = @mulAdd(f32, partial, activation_scale * weight_scale, acc);
        }
        out[r * n + c] = acc;
    };
}

test "GLM53 per-128 activation quantization uses amax over 448" {
    var x: [128]f32 = @splat(0);
    x[1] = 1;
    x[2] = -224;
    x[3] = 448;
    var q: [128]u8 = undefined;
    var s: [1]f32 = undefined;
    try quantize128(&x, 1, 128, &q, &s);
    try std.testing.expectEqual(@as(f32, 1), s[0]);
